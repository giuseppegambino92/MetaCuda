/*
 * test_cuda_basic.c — plain CUDA Driver API program (no MetaCuda-specific code).
 *
 * cuInit → device query → context → cuMemAlloc → cuMemcpyHtoD →
 * cuModuleLoadData(PTX) → cuModuleGetFunction → cuLaunchKernel →
 * cuMemcpyDtoH → verify.
 *
 * The PTX below is the verbatim output format of `nvcc -ptx` (CUDA 12.4) for:
 *
 *   __global__ void vectorAdd(const float *A, const float *B, float *C, int n) {
 *       int i = blockDim.x * blockIdx.x + threadIdx.x;
 *       if (i < n) C[i] = A[i] + B[i];
 *   }
 */
#include <cuda.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

static const char *PTX =
    "//\n"
    "// Generated by NVIDIA NVVM Compiler\n"
    "//\n"
    "// Compiler Build ID: CL-34097967\n"
    "// Cuda compilation tools, release 12.4, V12.4.131\n"
    "// Based on NVVM 7.0.1\n"
    "//\n"
    "\n"
    ".version 8.4\n"
    ".target sm_52\n"
    ".address_size 64\n"
    "\n"
    "\t// .globl\t_Z9vectorAddPKfS0_Pfi\n"
    "\n"
    ".visible .entry _Z9vectorAddPKfS0_Pfi(\n"
    "\t.param .u64 _Z9vectorAddPKfS0_Pfi_param_0,\n"
    "\t.param .u64 _Z9vectorAddPKfS0_Pfi_param_1,\n"
    "\t.param .u64 _Z9vectorAddPKfS0_Pfi_param_2,\n"
    "\t.param .u32 _Z9vectorAddPKfS0_Pfi_param_3\n"
    ")\n"
    "{\n"
    "\t.reg .pred \t%p<2>;\n"
    "\t.reg .f32 \t%f<4>;\n"
    "\t.reg .b32 \t%r<6>;\n"
    "\t.reg .b64 \t%rd<11>;\n"
    "\n"
    "\n"
    "\tld.param.u64 \t%rd1, [_Z9vectorAddPKfS0_Pfi_param_0];\n"
    "\tld.param.u64 \t%rd2, [_Z9vectorAddPKfS0_Pfi_param_1];\n"
    "\tld.param.u64 \t%rd3, [_Z9vectorAddPKfS0_Pfi_param_2];\n"
    "\tld.param.u32 \t%r2, [_Z9vectorAddPKfS0_Pfi_param_3];\n"
    "\tmov.u32 \t%r3, %ntid.x;\n"
    "\tmov.u32 \t%r4, %ctaid.x;\n"
    "\tmov.u32 \t%r5, %tid.x;\n"
    "\tmad.lo.s32 \t%r1, %r3, %r4, %r5;\n"
    "\tsetp.ge.s32 \t%p1, %r1, %r2;\n"
    "\t@%p1 bra \t$L__BB0_2;\n"
    "\n"
    "\tcvta.to.global.u64 \t%rd4, %rd1;\n"
    "\tmul.wide.s32 \t%rd5, %r1, 4;\n"
    "\tadd.s64 \t%rd6, %rd4, %rd5;\n"
    "\tcvta.to.global.u64 \t%rd7, %rd2;\n"
    "\tadd.s64 \t%rd8, %rd7, %rd5;\n"
    "\tld.global.f32 \t%f1, [%rd8];\n"
    "\tld.global.f32 \t%f2, [%rd6];\n"
    "\tadd.f32 \t%f3, %f2, %f1;\n"
    "\tcvta.to.global.u64 \t%rd9, %rd3;\n"
    "\tadd.s64 \t%rd10, %rd9, %rd5;\n"
    "\tst.global.f32 \t[%rd10], %f3;\n"
    "\n"
    "$L__BB0_2:\n"
    "\tret;\n"
    "\n"
    "}\n";

#define CHECK(call)                                                                       \
    do {                                                                                  \
        CUresult _r = (call);                                                             \
        if (_r != CUDA_SUCCESS) {                                                         \
            const char *_s = NULL;                                                        \
            cuGetErrorName(_r, &_s);                                                      \
            fprintf(stderr, "FAIL %s:%d: %s -> %s (%d)\n", __FILE__, __LINE__, #call, _s, _r); \
            exit(1);                                                                      \
        }                                                                                 \
    } while (0)

int main(void) {
    CHECK(cuInit(0));
    int ver = 0, count = 0;
    CHECK(cuDriverGetVersion(&ver));
    CHECK(cuDeviceGetCount(&count));
    CUdevice dev;
    CHECK(cuDeviceGet(&dev, 0));
    char name[256];
    CHECK(cuDeviceGetName(name, sizeof name, dev));
    size_t mem = 0;
    CHECK(cuDeviceTotalMem(&mem, dev));
    int major = 0, minor = 0, sms = 0;
    CHECK(cuDeviceGetAttribute(&major, CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MAJOR, dev));
    CHECK(cuDeviceGetAttribute(&minor, CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MINOR, dev));
    CHECK(cuDeviceGetAttribute(&sms, CU_DEVICE_ATTRIBUTE_MULTIPROCESSOR_COUNT, dev));
    printf("driver %d.%d | %d device(s) | %s | %.1f GiB | sm_%d%d | %d SMs\n", ver / 1000, (ver % 1000) / 10, count, name, mem / 1073741824.0,
           major, minor, sms);

    CUcontext ctx;
    CHECK(cuCtxCreate(&ctx, 0, dev));

    const int n = 1 << 20;
    size_t bytes = n * sizeof(float);
    float *ha = malloc(bytes), *hb = malloc(bytes), *hc = malloc(bytes);
    for (int i = 0; i < n; i++) { ha[i] = (float)i * 0.5f; hb[i] = (float)(n - i) * 0.25f; }

    CUdeviceptr da, db, dc;
    CHECK(cuMemAlloc(&da, bytes));
    CHECK(cuMemAlloc(&db, bytes));
    CHECK(cuMemAlloc(&dc, bytes));
    CHECK(cuMemcpyHtoD(da, ha, bytes));
    CHECK(cuMemcpyHtoD(db, hb, bytes));
    CHECK(cuMemsetD32(dc, 0, n));

    CUmodule mod;
    CUfunction fn;
    CHECK(cuModuleLoadData(&mod, PTX));
    CHECK(cuModuleGetFunction(&fn, mod, "_Z9vectorAddPKfS0_Pfi"));

    int threads = 256, blocks = (n + threads - 1) / threads;
    int nn = n;
    void *args[] = {&da, &db, &dc, &nn};
    CHECK(cuLaunchKernel(fn, blocks, 1, 1, threads, 1, 1, 0, NULL, args, NULL));
    CHECK(cuCtxSynchronize());
    CHECK(cuMemcpyDtoH(hc, dc, bytes));

    int errors = 0;
    for (int i = 0; i < n; i++)
        if (fabsf(hc[i] - (ha[i] + hb[i])) > 1e-5f * fabsf(ha[i] + hb[i])) {
            if (errors++ < 5) fprintf(stderr, "mismatch at %d: %f != %f\n", i, hc[i], ha[i] + hb[i]);
        }
    printf("vectorAdd: %d elements, %d blocks x %d threads, device ptrs 0x%llx 0x%llx 0x%llx -> %s\n", n, blocks, threads,
           (unsigned long long)da, (unsigned long long)db, (unsigned long long)dc, errors ? "FAILED" : "PASSED");

    CHECK(cuMemFree(da));
    CHECK(cuMemFree(db));
    CHECK(cuMemFree(dc));
    CHECK(cuModuleUnload(mod));
    CHECK(cuCtxDestroy(ctx));
    free(ha); free(hb); free(hc);
    return errors ? 1 : 0;
}
